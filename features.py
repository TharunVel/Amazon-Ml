"""
Stage 4: Pairwise Feature Engineering

Takes the candidate pairs generated by Blocking (Stage 3) and computes
pairwise similarity features (Jaccard, Levenshtein, etc.) for the ML classifier.
Uses Pandas merging and vectorization for speed without IPC overhead.
"""

import os
import time
import argparse
import numpy as np
import pandas as pd
import jellyfish

def get_char_ngrams(text, n=3):
    if not text or pd.isna(text):
        return set()
    text = str(text)
    return set(text[i:i+n] for i in range(len(text)-n+1))

def jaccard(set1, set2):
    if not set1 and not set2:
        return 0.0
    if not set1 or not set2:
        return 0.0
    return len(set1 & set2) / len(set1 | set2)

def compute_row_features(row):
    n1, n2 = str(row['name_clean_x']), str(row['name_clean_y'])
    t1, t2 = set(str(row['name_tokens_sorted_x']).split()), set(str(row['name_tokens_sorted_y']).split())
    a1, a2 = str(row['addr_numbers_x']), str(row['addr_numbers_y'])
    c1, c2 = str(row['country_clean_x']), str(row['country_clean_y'])
    
    # New columns
    addr_txt1, addr_txt2 = str(row['addr_clean_x']), str(row['addr_clean_y'])

    # Name features
    name_exact = int(n1 == n2 and n1 != '')
    name_jaccard_word = jaccard(t1, t2)
    name_jaccard_char3 = jaccard(get_char_ngrams(n1, 3), get_char_ngrams(n2, 3))
    name_jaro_winkler = jellyfish.jaro_winkler_similarity(n1, n2) if n1 and n2 else 0.0
    name_levenshtein = jellyfish.damerau_levenshtein_distance(n1, n2) if n1 and n2 else 999

    # Address features
    addr_num_exact = int(a1 == a2 and a1 != '')
    addr_jaccard_word = jaccard(set(addr_txt1.split()), set(addr_txt2.split()))
    addr_jaro_winkler = jellyfish.jaro_winkler_similarity(addr_txt1, addr_txt2) if addr_txt1 and addr_txt2 else 0.0

    country_exact = int(c1 == c2 and c1 != '')

    return pd.Series([
        name_exact, name_jaccard_word, name_jaccard_char3, 
        name_jaro_winkler, name_levenshtein, 
        addr_num_exact, addr_jaccard_word, addr_jaro_winkler,
        country_exact
    ])

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--candidate-path", default="output/val_10k_candidate_pairs.tsv")
    parser.add_argument("--s1-path", default="preprocessed/train/train_source1.tsv")
    parser.add_argument("--s2-path", default="preprocessed/train/train_source2.tsv")
    parser.add_argument("--s3-path", default="preprocessed/train/train_source3.tsv")
    parser.add_argument("--output-path", default="output/val_10k_features.csv")
    args = parser.parse_args()

    print("Loading candidate pairs...", flush=True)
    cands_df = pd.read_csv(args.candidate_path, sep='\t')
    
    # Flatten candidate pairs
    pairs = []
    for _, row in cands_df.iterrows():
        s1 = row['source1_entity_id']
        cands = str(row['candidate_entity_ids']).split(',')
        for c in cands:
            if c and c != 'nan':
                pairs.append({'source1_entity_id': s1, 'candidate_entity_id': c})
                
    pairs_df = pd.DataFrame(pairs)
    print(f"Total pairs to process: {len(pairs_df):,}", flush=True)
    
    if len(pairs_df) == 0:
        print("No pairs to process.")
        return

    print("Loading source datasets...", flush=True)
    cols = ['entity_id', 'name_clean', 'name_tokens_sorted', 'addr_numbers', 'country_clean', 'addr_clean']
    
    s1 = pd.read_csv(args.s1_path, sep='\t', usecols=cols).fillna('')
    s2 = pd.read_csv(args.s2_path, sep='\t', usecols=cols).fillna('')
    s3 = pd.read_csv(args.s3_path, sep='\t', usecols=cols).fillna('')
    s23 = pd.concat([s2, s3])
    del s2, s3

    print("Extracting features in chunks...", flush=True)
    t0 = time.time()
    
    chunk_size = 500000
    out_dfs = []
    
    for i in range(0, len(pairs_df), chunk_size):
        chunk = pairs_df.iloc[i:i+chunk_size]
        
        # Merge with S1 data
        merged = chunk.merge(s1, left_on='source1_entity_id', right_on='entity_id', how='inner')
        # Merge with S2/S3 data
        merged = merged.merge(s23, left_on='candidate_entity_id', right_on='entity_id', how='inner')
        
        if len(merged) == 0:
            continue
            
        # Compute features
        feats = merged.apply(compute_row_features, axis=1)
        feats.columns = ['name_exact', 'name_jaccard_word', 'name_jaccard_char3', 
                         'name_jaro_winkler', 'name_levenshtein', 
                         'addr_num_exact', 'addr_jaccard_word', 'addr_jaro_winkler',
                         'country_exact']
        
        res = pd.concat([merged[['source1_entity_id', 'candidate_entity_id']], feats], axis=1)
        out_dfs.append(res)
        
        print(f"  Processed {min(i+chunk_size, len(pairs_df)):,}/{len(pairs_df):,} pairs ({(time.time()-t0):.1f}s)", flush=True)

    print(f"Done computing in {time.time()-t0:.1f}s", flush=True)
    
    final_df = pd.concat(out_dfs, ignore_index=True)
    final_df.to_csv(args.output_path, index=False)
    print(f"Saved features to {args.output_path}")

if __name__ == "__main__":
    main()
